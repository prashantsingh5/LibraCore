from dataclasses import dataclass
from enum import Enum
from uuid import uuid4
from pydantic import ValidationError, TypeAdapter
from .. import schemas as s
from ..services import DomainError

class Action(str, Enum):
    READ = 'READ'
    WRITE = 'WRITE'
    HIGH_RISK = 'HIGH_RISK'

@dataclass(frozen=True)
class Tool:
    name: str
    description: str
    schema: type[s.Input]
    action: Action

TOOLS = {t.name:t for t in [
    Tool('search_resources','Search resources with combined filters and pagination',s.Search,Action.READ),
    Tool('get_resource','Read resource metadata',s.ResourceId,Action.READ),
    Tool('get_availability','Read current available copies or seats',s.ResourceId,Action.READ),
    Tool('get_budget_summary','Read default or department budget',s.Department,Action.READ),
    Tool('get_department_budget','Read department budget',s.Department,Action.READ),
    Tool('quote_purchase','Obtain authoritative C++ price',s.Purchase,Action.READ),
    Tool('check_purchase','Check C++ budget and quota validation without buying',s.Purchase,Action.READ),
    Tool('submit_purchase','Purchase resources; requires confirmation',s.Submit,Action.HIGH_RISK),
    Tool('cancel_purchase','Cancel a purchase; requires confirmation',s.Cancel,Action.HIGH_RISK),
    Tool('borrow_resource','Borrow for a persistent user',s.Borrow,Action.WRITE),
    Tool('return_loan','Return quantity against a loan',s.Return,Action.WRITE),
    Tool('get_order','Read order status and immutable record',s.OrderId,Action.READ),
    Tool('get_user_loans','Read user loans',s.UserId,Action.READ),
    Tool('get_recent_events','Read audit history',s.Page,Action.READ),
]}

def declarations():
    result=[]
    for tool in TOOLS.values():
        schema=tool.schema.model_json_schema()
        # Request IDs are generated by the application, never selected by the model.
        schema.get('properties', {}).pop('request_id',None)
        schema['required']=[k for k in schema.get('required',[]) if k!='request_id']
        schema.pop('additionalProperties',None)
        result.append({'name':tool.name,'description':tool.description,'parameters':schema})
    return result

def validate_call(call):
    if call.name not in TOOLS:
        raise DomainError('UNKNOWN_TOOL','Unknown tool requested')
    tool=TOOLS[call.name]
    args=dict(call.arguments)
    if 'request_id' in args:
        raise DomainError('INVALID_TOOL','Model cannot choose request identifiers')
    if tool.action != Action.READ:
        args['request_id']=str(uuid4())
    try:
        parsed=tool.schema.model_validate(args)
    except (ValidationError, TypeError, ValueError):
        raise DomainError('INVALID_TOOL','Invalid tool parameters') from None
    return tool, parsed.model_dump(mode='json',exclude_none=True)

OUTPUTS = {
    'search_resources': s.SearchOutput, 'get_resource': s.ResourceOutput,
    'get_availability': s.AvailabilityOutput, 'get_budget_summary': s.BudgetOutput,
    'get_department_budget': s.BudgetOutput, 'quote_purchase': s.QuoteOutput,
    'check_purchase': s.CheckOutput, 'submit_purchase': s.OrderOutput,
    'cancel_purchase': s.OrderOutput, 'borrow_resource': s.LoanOutput,
    'return_loan': s.LoanOutput, 'get_order': s.OrderOutput,
    'get_user_loans': list[s.LoanOutput], 'get_recent_events': list[s.EventOutput],
}

def validate_output(name, value):
    try:
        adapter=TypeAdapter(OUTPUTS[name])
        return adapter.dump_python(adapter.validate_python(value),mode='json')
    except ValidationError:
        raise DomainError('INTERNAL_ERROR','Application returned an invalid tool result') from None
